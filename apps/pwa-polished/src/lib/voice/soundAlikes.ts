/** The word a heard word most likely is in the Bible. */
export function bibleWord(heard: unknown): string {
  const w = String(heard ?? '').toLowerCase().trim();
  const group = SOUNDALIKES.find((g) => g.some(([x]) => x === w));
  if (!group) return w;
  const [best, most] = group.reduce((a, b) => (b[1] > a[1] ? b : a));
  return most >= 5 * group.find(([x]) => x === w)![1] ? best : w;
}
