/**
 * How often each classic Strong's number is used, for the Strong's list's
 * "114×" and its Most used order.
 *
 * Written into the app as a small JSON file rather than into the lexical pack:
 * a pack change would make every reader re-download 372 MB for a column of
 * numbers.
 *
 * Counted in one text per testament so the numbers mean something fixed:
 *   Greek   the Byzantine text (BYZ); a word it lacks falls back to the TR
 *   Hebrew  the Westminster/OSHB text
 * Split meanings fold into their number (G2424G and G2424K both count toward
 * G2424), because the list has one row per classic number.
 *
 * Usage: node scripts/build-strongs-counts.mjs [path/to/ancient-languages.sqlite]
 */

import fs from 'node:fs';
import path from 'node:path';
import Database from 'better-sqlite3';

const repoRoot = path.resolve('.');
const packPath =
  process.argv[2] ?? path.join(repoRoot, 'packs', 'consolidated', 'ancient-languages.sqlite');
const outPath = path.join(repoRoot, 'apps', 'pwa-polished', 'src', 'data', 'strongs-counts.json');

/** The last classic number in each language. */
const LAST = { G: 5624, H: 8674 };

if (!fs.existsSync(packPath)) {
  console.error(`Missing ancient-languages pack at ${packPath}`);
  process.exit(1);
}

const db = new Database(packPath, { readonly: true });

/** number → uses, for one text, splits folded in. */
function countsFor(translationId, prefix) {
  const out = new Array(LAST[prefix] + 1).fill(0);
  const rows = db
    .prepare('SELECT strongs, COUNT(*) AS n FROM words WHERE translation_id = ? AND strongs LIKE ? GROUP BY strongs')
    .all(translationId, `${prefix}%`);
  for (const { strongs, n } of rows) {
    const m = /^[GH]0*(\d+)[A-Za-z]?$/.exec(strongs ?? '');
    if (!m) continue;
    const num = Number(m[1]);
    if (num >= 1 && num <= LAST[prefix]) out[num] += n;
  }
  return out;
}

const byz = countsFor('byz', 'G');
const tr = countsFor('tr', 'G');
const greek = byz.map((n, i) => n || tr[i]);
const hebrew = countsFor('hebrew-oshb', 'H');
db.close();

const used = (list) => list.filter((n) => n > 0).length;
fs.writeFileSync(
  outPath,
  JSON.stringify({
    note: 'Generated by scripts/build-strongs-counts.mjs. Index = Strong’s number; Greek from BYZ (TR where BYZ lacks it), Hebrew from OSHB.',
    greek,
    hebrew,
  }) + '\n',
);

console.log(`Greek: ${used(greek)} of ${LAST.G} numbers used (G26 = ${greek[26]}, G2424 = ${greek[2424]})`);
console.log(`Hebrew: ${used(hebrew)} of ${LAST.H} numbers used (H430 = ${hebrew[430]}, H1254 = ${hebrew[1254]})`);
console.log(`Wrote ${path.relative(repoRoot, outPath)} (${fs.statSync(outPath).size} bytes)`);
