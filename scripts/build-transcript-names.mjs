/**
 * The Bible's names, for capitals in transcripts (apps/pwa-polished/src/lib/voice/bibleNames.ts).
 *
 * A name is a word the KJV, WEB and BSB write with a capital in the middle of
 * a sentence at least 90% of the times they use it there, at least twice:
 * people, places, God, Lord, Jesus, the Pharisees. Words that open a
 * sentence or a verse, or follow a quote mark, aren't counted either way.
 *
 * Names that are everyday English words too (Job, Mark, Eve, Ham) are kept
 * apart: the English dictionary pack gives them two or more meanings of their
 * own. A transcript capitalizes those only when the words around them say so
 * ("the book of Job", "Mark 5", "Adam and Eve").
 *
 * Run from the repo root after the translations pack changes:
 *   node scripts/build-transcript-names.mjs
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import Database from 'better-sqlite3';
import { stripFootnotes, stripHtml } from './lib/clean-text.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PACKS = join(root, 'packs', 'consolidated');
const OUT = join(root, 'apps', 'pwa-polished', 'src', 'lib', 'voice', 'bibleNames.ts');

const TRANSLATIONS = ['kjv', 'web', 'bsb'];
/** Always a capital, whatever the dictionary says: English capitalizes these too. */
const ALWAYS = new Set(`god lord jesus christ messiah israel jerusalem arabian armageddon chaldean christian
  clement egyptian epicurean galilean gentile greek hebrew italian judas latin moloch nazarene philistine
  phoenix roman stoic timothy shibboleth`.split(/\s+/));
/** Names that are everyday words too, kept for the words around them to decide. The rest of those are dropped. */
const IN_CONTEXT = new Set('job eve gad ham nun psalm salmon alpha omega'.split(' '));
/**
 * Never a name in speech, whatever the Bible does: the KJV's "Ah" and
 * "Nevertheless" mid-sentence, a place called Beer, the title words.
 */
const NEVER = new Set(`ah beer er nevertheless tidal tartan shisha pinon maim deity protector rabbi zealot mica
  hod i'm`.split(/\s+/));

const tx = new Database(join(PACKS, 'translations.sqlite'), { readonly: true });
const dict = new Database(join(PACKS, 'dictionary-en.sqlite'), { readonly: true });

/** word → { cap, low, forms } */
const seen = new Map();
const WORD_RE = /[A-Za-z]+(?:['’-][A-Za-z]+)*/g;

for (const t of TRANSLATIONS) {
  const rows = tx.prepare('SELECT text FROM verses WHERE translation_id = ?').all(t);
  for (const { text } of rows) {
    const clean = stripHtml(stripFootnotes(text)).replace(/[\x00-\x1f]/g, ' ');
    let first = true;
    for (const m of clean.matchAll(WORD_RE)) {
      const word = m[0];
      const before = clean.slice(Math.max(0, m.index - 3), m.index);
      const opens = first || /[.!?:;“"‘(\[]\s*$/.test(before) || /['’]\s*$/.test(before);
      first = false;
      if (opens || word.length < 2) continue;
      const key = word.toLowerCase().replace(/’/g, "'");
      let s = seen.get(key);
      if (!s) seen.set(key, (s = { cap: 0, low: 0, forms: new Map() }));
      if (/^[A-Z]/.test(word)) {
        s.cap++;
        // "LORD" is written that way for the divine name; spoken, it's Lord.
        const form = word === word.toUpperCase() ? word[0] + word.slice(1).toLowerCase() : word.replace(/’/g, "'");
        s.forms.set(form, (s.forms.get(form) || 0) + 1);
      } else {
        s.low++;
      }
    }
  }
}

const meanings = dict.prepare(
  'SELECT COUNT(*) AS n FROM english_definitions_wordset d JOIN word_mapping m ON m.word_id = d.word_id WHERE m.lemma = ?',
);

const names = [];
const everyday = [];
for (const [key, s] of seen) {
  if (s.cap < 2 || s.cap / (s.cap + s.low) < 0.9) continue;
  const form = [...s.forms].sort((a, b) => b[1] - a[1])[0][0];
  // Hyphenated KJV spellings ("Beth-el") are said as one word.
  // Possessives ("Aaron's") are matched by their name.
  if (/-/.test(form) || /'s$/.test(key) || NEVER.has(key)) continue;
  if (IN_CONTEXT.has(key)) everyday.push(form);
  else if (ALWAYS.has(key) || meanings.get(key).n < 2) names.push(form);
}
names.sort((a, b) => a.localeCompare(b));
everyday.sort((a, b) => a.localeCompare(b));

const wrap = (list) => {
  const lines = [];
  let line = '';
  for (const w of list) {
    if ((line + ' ' + w).length > 100) {
      lines.push(line);
      line = w;
    } else line = line ? line + ' ' + w : w;
  }
  if (line) lines.push(line);
  return lines.map((l) => `  ${l}`).join('\n');
};

writeFileSync(
  OUT,
  `/**
 * The Bible's names, for capitals in transcripts. Generated by
 * scripts/build-transcript-names.mjs from the KJV, WEB and BSB: every word they
 * write with a capital in the middle of a sentence nine times in ten.
 * Don't edit by hand; run the script again.
 */

/** Always capitalized, written as the Bible writes them. */
export const BIBLE_NAMES: string[] = \`
${wrap(names)}
\`.trim().split(/\\s+/);

/** Names that are everyday words too: capitalized only when the words around them say so. */
export const EVERYDAY_NAMES: string[] = \`
${wrap(everyday)}
\`.trim().split(/\\s+/);
`,
);

console.log(`${names.length} names, ${everyday.length} that are everyday words too → ${OUT}`);
console.log('Everyday:', everyday.join(' '));
