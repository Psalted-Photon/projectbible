/**
 * Turns the Name Lab's fixes (scripts/name-fixes.txt) into what the app reads
 * (apps/pwa-polished/src/lib/tts/pronunciationData.ts).
 *
 * It works each fix out again with the app's own text-to-sounds step and stops
 * if the result isn't what the lab said it would say, so what Read Aloud plays
 * is what was heard in the lab.
 *
 * Run from the repo root after name-fixes.txt changes:
 *   node scripts/build-pronunciations.mjs
 */

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { moveStress, plainLetters, syllables, withoutStress } from '../apps/pwa-polished/public/name-lab-sounds.js';
import { bibleWordCounts, readNameFixes, soundsFor } from './lib/name-sounds.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'apps', 'pwa-polished', 'src', 'lib', 'tts', 'pronunciationData.ts');

const fixes = readNameFixes();
const said = fixes.map((f) => f.spell ?? f.name);
const accents = [
  { key: 'us', code: 'en-us', says: 'saysUs' },
  { key: 'uk', code: 'en-gb-x-rp', says: 'saysUk' },
];

const spellings = {};
const stress = { us: {}, uk: {} };

for (const fix of fixes) if (fix.spell) spellings[fix.name] = fix.spell;

for (const { key, code, says } of accents) {
  const sounds = await soundsFor(said, code);
  fixes.forEach((fix, i) => {
    const final = fix.strong ? moveStress(sounds[i], fix.strong - 1) : sounds[i];
    if (fix.strong) {
      const count = syllables(sounds[i]).length;
      if (fix.strong > count) throw new Error(`${fix.name} has ${count} syllables in ${key}, so it can't lean on ${fix.strong}`);
      // Stress is found word by word in a verse's sounds, so a fix can't span two.
      if (/\s/.test(sounds[i])) throw new Error(`${fix.name}: a strong syllable on a two-word spelling isn't supported`);
      stress[key][withoutStress(sounds[i])] = final;
    }
    if (fix[says] && plainLetters(final) !== fix[says]) {
      throw new Error(`${fix.name} in ${key} says ${plainLetters(final)}, but the lab heard ${fix[says]}`);
    }
  });
}

// A word Whistle writes only stands for the name if the Bible uses the name at
// least 5 times as often, the rule soundAlikes.ts uses, so a real word that
// matters stays itself.
const counts = bibleWordCounts();
const heardAs = {};
const leftOut = [];
for (const fix of fixes) {
  const named = counts.get(fix.name) || 0;
  for (const word of fix.hear) {
    if (!/^[a-z']+$/.test(word)) throw new Error(`${fix.name}: "${word}" has to be one small-letter word`);
    const used = (counts.get(word) || 0) + (counts.get(word[0].toUpperCase() + word.slice(1)) || 0);
    if (named >= 5 * used) heardAs[word] = fix.name;
    else leftOut.push(`${word} for ${fix.name} (${word} ${used}, ${fix.name} ${named})`);
  }
}

const entries = (table) =>
  Object.entries(table).map(([from, to]) => `  ${JSON.stringify(from)}: ${JSON.stringify(to)},`).join('\n');
const block = (table) => (Object.keys(table).length ? `{\n${entries(table)}\n}` : '{}');

writeFileSync(
  OUT,
  `/**
 * How the voices should say names. Generated by scripts/build-pronunciations.mjs
 * from scripts/name-fixes.txt, so change it there and not here.
 */

/** A name as written, and the spelling that gets the voices to say it right. */
export const SPELLINGS: Record<string, string> = ${block(spellings)};

/** A word's sounds with the stress marks taken out, and what to say instead, per accent. */
export const STRONG_US: Record<string, string> = ${block(stress.us)};
export const STRONG_UK: Record<string, string> = ${block(stress.uk)};

/** A word Whistle writes, and the name it stands for in a voice command. */
export const HEARD_AS: Record<string, string> = ${block(heardAs)};
`,
);
console.log(`→ ${OUT}\n${Object.keys(spellings).length} spellings, ${Object.keys(stress.us).length} strong syllables, ${Object.keys(heardAs).length} words for commands`);
if (leftOut.length) console.log(`Left out of commands, too common in the Bible: ${leftOut.join('; ')}`);
